"""Rebuild data/publications.bib from the SCI publications database.

    published = exclude_and_add(cleanup(select(patch(source))))

    source           data/source/sci.bib: the database export exactly as fetched, never edited by hand
    patch            "patch" overrides in data/publications-overrides.json: per-entry field fixes; they come first so a
                     fixed author list can bring an entry into the selection
    select           the "selection" section of data/publications-rules.json
    cleanup          the "rules" of data/publications-rules.json, applied in order; each rule states why it exists
    exclude_and_add  "exclude" and "add" overrides
Every override carries a reason, and every rule and override that applied is listed in the commit message.

The fetch is a conditional GET (If-None-Match / If-Modified-Since): when the export has not changed, the server
answers 304 with no body and nothing is written. Standard library only, so it runs on a stock GitHub runner.

usage: python3 scripts/sync_publications.py [--no-fetch | --source-file PATH] [--commit-message-file PATH]
    --no-fetch      rebuild from the stored export, after editing the rule book or the overrides
    --source-file   use a manually downloaded export (e.g. if the server blocks the scheduled job)
Exits with status 1, writing nothing, when the fetch or a safety check fails.
"""
import argparse
import hashlib
import json
import re
import sys
import textwrap
import unicodedata
import urllib.error
import urllib.request
from dataclasses import dataclass
from pathlib import Path

REPOSITORY = Path(__file__).resolve().parent.parent
DATA = REPOSITORY / "data"
SOURCE_PATH = DATA / "source" / "sci.bib"
FETCH_STATE_PATH = DATA / "source" / "fetch-state.json"
RULES_PATH = DATA / "publications-rules.json"
OVERRIDES_PATH = DATA / "publications-overrides.json"
PUBLISHED_PATH = DATA / "publications.bib"
USER_AGENT = "MULTI-website-publication-sync (+https://github.com/SCIInstitute/MULTI-website)"
TIMEOUT_SECONDS = 30
PUBLISHED_HEADER = ("% Generated by scripts/sync_publications.py from the SCI publications database. Do not edit this file:\n"
                    "% change data/publications-rules.json or data/publications-overrides.json and rerun the script.\n\n")

# The website's own parser (js/multi.js parseBibtex / parseBibtexFields), used to check that it reads what we write.
SITE_ENTRY_PATTERN = re.compile(r"@(\w+)\{([^,]+),([^@]+)\}")
SITE_FIELD_PATTERN = re.compile(r"(\w+)\s*=\s*[\"{]([^\"{}]+(?:\{[^{}]*\}[^\"{}]*)*)[\"}]", re.IGNORECASE)


class SyncError(Exception):
    pass


@dataclass
class Entry:
    entry_type: str
    key: str
    fields: dict


def parse_bibtex(text):
    """-> (entries in file order, {key: error} for entries that cannot be read). Each entry is parsed on its own, so
    one malformed record in the database does not stop the others. A value is "..." (braces may nest inside, so
    {\\"o} is fine), {...}, or a bare token such as 2026. Text outside entries (the %%: header) is skipped."""
    entries, errors = [], {}
    for chunk in re.split(r"\n(?=@\w+\{)", text):
        match = re.compile(r"\s*@(\w+)\{([^,\s]+),").match(chunk)
        if not match:
            continue
        try:
            entries.append(Entry(match.group(1), match.group(2), parse_fields(chunk, match.end(), match.group(2))))
        except SyncError as error:
            errors[match.group(2)] = str(error)
    return entries, errors


def parse_fields(chunk, position, key):
    fields = {}
    while not re.compile(r"\s*\}").match(chunk, position):
        name = re.compile(r"\s*(\w+)\s*=\s*").match(chunk, position)
        if not name:
            raise SyncError(f"{key}: cannot read a field at {chunk[position:position + 60]!r}")
        fields[name.group(1).lower()], position = read_value(chunk, name.end(), key)
        if comma := re.compile(r"\s*,").match(chunk, position):
            position = comma.end()
    return fields


def read_value(text, position, key):
    """-> (value without its delimiters, position after it). Strict BibTeX ends a "..." value at the first " outside
    braces, but the database has titles with bare quotes inside (SCI:Lis2023a), so a " only closes the value when
    the next non-space character is , or }."""
    opening = text[position:position + 1]
    if opening in ('"', "{"):
        depth = 0
        for index in range(position + 1, len(text)):
            character = text[index]
            if (opening == '"' and character == '"' and depth == 0
                    and re.compile(r"\s*[,}]").match(text, index + 1)):
                return text[position + 1:index], index + 1
            if character == "{":
                depth += 1
            elif character == "}":
                if opening == "{" and depth == 0:
                    return text[position + 1:index], index + 1
                depth -= 1
        raise SyncError(f"{key}: value never closes")
    bare = re.compile(r"[\w.-]+").match(text, position)
    if not bare:
        raise SyncError(f"{key}: cannot read a value at {text[position:position + 60]!r}")
    return bare.group(0), bare.end()


def split_authors(value):
    return [name for name in re.split(r"\s+and\s+(?:and\s+)*", value.strip()) if name]


def name_key(name):
    return re.sub(r"[\s.]", "", name).lower()


def is_selected(entry, selection):
    wanted = {name_key(name) for name in selection["anyName"]}
    return any(name_key(person) in wanted
               for field in selection["inFields"] for person in split_authors(entry.fields.get(field, "")))


def apply_rule(rule, value):
    if rule["type"] == "literal":
        return value.replace(rule["find"], rule["replace"])
    if rule["type"] == "regex":
        return re.sub(rule["pattern"], rule["replacement"], value)
    if rule["type"] == "latexAccents":
        symbols = "".join(re.escape(symbol) for symbol in rule["combiningMarks"])
        # {\"o}, \"{o}, {\"{o}} and \"o; the conditional groups (?(1)...) keep the braces balanced.
        pattern = rf"(\{{)?\\([{symbols}])(\{{)?([A-Za-z])(?(3)\}})(?(1)\}})"
        return re.sub(pattern, lambda match: unicodedata.normalize("NFC", match.group(4) + rule["combiningMarks"][match.group(2)]), value)
    raise SyncError(f"rule {rule['id']}: unknown type {rule['type']!r}")


def clean(entries, rules):
    """Applies the rules in place; -> {rule id: keys of the entries it changed}."""
    changed_keys = {rule["id"]: [] for rule in rules}
    for entry in entries:
        for rule in rules:
            changed = False
            for name, value in entry.fields.items():
                if rule["fields"] == "all" or name in rule["fields"]:
                    new_value = apply_rule(rule, value)
                    changed |= new_value != value
                    entry.fields[name] = new_value
            if changed:
                changed_keys[rule["id"]].append(entry.key)
    return changed_keys


def apply_patches(source_entries, overrides):
    """In place; -> log lines. An override that no longer applies is an error, so stale overrides get removed."""
    by_key = {entry.key: entry for entry in source_entries}
    log = []
    for item in overrides["patch"]:
        if item["key"] not in by_key:
            raise SyncError(f"patch override {item['key']}: the database has no such entry; remove the override")
        if all(by_key[item["key"]].fields.get(name) == value for name, value in item["fields"].items()):
            raise SyncError(f"patch override {item['key']}: the database already has these values; remove the override")
        by_key[item["key"]].fields.update(item["fields"])
        log.append(f"patched {item['key']} ({', '.join(item['fields'])}): {item['reason']}")
    return log


def exclude_and_add(entries, overrides, source_keys):
    """-> (entries, log lines)."""
    by_key = {entry.key: entry for entry in entries}
    log = []
    for item in overrides["exclude"]:
        if by_key.pop(item["key"], None) is None:
            raise SyncError(f"exclude override {item['key']}: no such selected entry; remove the override")
        log.append(f"excluded {item['key']}: {item['reason']}")
    for item in overrides["add"]:
        if item["key"] in source_keys:
            raise SyncError(f"add override {item['key']}: the database now has this entry; remove the override "
                            "or turn it into a patch")
        by_key[item["key"]] = Entry(item["type"], item["key"], dict(item["fields"]))
        log.append(f"added {item['key']}: {item['reason']}")
    return list(by_key.values()), log


def year_of(entry):
    return int(entry.fields["year"]) if entry.fields.get("year", "").isdigit() else 0


def format_bibtex(entries):
    blocks = ["\n".join([f"@{entry.entry_type}{{{entry.key},"] + [f'  {name} = "{value}",' for name, value in entry.fields.items()] + ["}"])
              for entry in entries]
    return PUBLISHED_HEADER + "\n\n".join(blocks) + "\n"


def site_parser_problems(published_text, entries):
    """Entries the website would drop or misread, using the website's own regular expressions."""
    site_entries = {}
    for match in SITE_ENTRY_PATTERN.finditer(published_text):
        site_entries[match.group(2).strip()] = {field.group(1).lower(): re.sub(r"\s+", " ", field.group(2)).strip()
                                                for field in SITE_FIELD_PATTERN.finditer(match.group(3))}
    problems = []
    for entry in entries:
        if entry.key not in site_entries:
            problems.append(f"{entry.key}: the website's parser skips this entry (an @ or a stray brace in a value)")
            continue
        for name in ("author", "title", "year"):
            if name in entry.fields and site_entries[entry.key].get(name) != entry.fields[name]:
                problems.append(f"{entry.key}: the website would read {name} as {site_entries[entry.key].get(name)!r}")
    return problems


def leftover_latex(entries):
    return [f"{entry.key}: LaTeX left in {name}: {value!r}" for entry in entries for name, value in entry.fields.items()
            if re.search(r"\\|\$", value)]


def identity(entry):
    if entry.fields.get("doi"):
        return "doi:" + entry.fields["doi"].lower()
    return "title:" + re.sub(r"[^a-z0-9]", "", entry.fields.get("title", "").lower())


def describe_changes(previous_entries, entries):
    previous = {entry.key: entry for entry in previous_entries}
    current = {entry.key: entry for entry in entries}
    added = [key for key in current if key not in previous]
    removed = [key for key in previous if key not in current]
    renamed = []
    for old_key in list(removed):
        new_key = next((key for key in added if identity(current[key]) == identity(previous[old_key])), None)
        if new_key:
            renamed.append((old_key, new_key))
            removed.remove(old_key)
            added.remove(new_key)
    changed = [(key, [name for name in sorted(set(previous[key].fields) | set(current[key].fields))
                      if previous[key].fields.get(name) != current[key].fields.get(name)])
               for key in current if key in previous]
    return {"added": [current[key] for key in added], "removed": [previous[key] for key in removed], "renamed": renamed,
            "changed": [(key, names) for key, names in changed if names]}


def fetch(url, state):
    """-> (bytes, response validators), or (None, None) if the server says the export is unchanged (304)."""
    headers = {"User-Agent": USER_AGENT}
    if state.get("etag"):
        headers["If-None-Match"] = state["etag"]
    if state.get("lastModified"):
        headers["If-Modified-Since"] = state["lastModified"]
    try:
        with urllib.request.urlopen(urllib.request.Request(url, headers=headers), timeout=TIMEOUT_SECONDS) as response:
            return response.read(), {"etag": response.headers.get("ETag"), "lastModified": response.headers.get("Last-Modified")}
    except urllib.error.HTTPError as error:
        if error.code == 304:
            return None, None
        raise SyncError(f"{url} answered HTTP {error.code} {error.reason}. A 403 or 429 may mean the server is blocking "
                        "or rate limiting this job: ask SCI IT before retrying.")
    except (urllib.error.URLError, TimeoutError) as error:
        raise SyncError(f"could not reach {url}: {error}")


def wrap(text, indent):
    return textwrap.fill(text, width=100, initial_indent=indent, subsequent_indent=indent + "  ")


def commit_message(origin, rebuilt, export_header, num_source_entries, num_selected, changes, rule_hits, rules,
                   override_log, attention):
    counts = {name: len(changes[name]) for name in ("added", "removed", "renamed", "changed")}
    summary = ", ".join(f"{count} {name}" for name, count in counts.items() if count) or "no published entry changed"
    if rebuilt:
        subject = f"Rebuild publications after a rule book or override change: {summary}"
    elif any(counts.values()):
        subject = f"Sync publications with the SCI database: {summary}"
    else:
        subject = "Record new SCI database export; no published entry changed"
    lines = [subject, "", wrap(f"Source: {origin}. Export header: \"{export_header}\". {num_source_entries} entries, "
                               f"{num_selected} selected by the rule book's selection rule.", "")]
    sections = [
        ("Added", [f"{entry.key} ({entry.fields.get('year', '?')}) {entry.fields.get('title', '')}" for entry in changes["added"]]),
        ("Removed from the database", [f"{entry.key} ({entry.fields.get('year', '?')}) {entry.fields.get('title', '')}"
                                       for entry in changes["removed"]]),
        ("Renamed in the database (same DOI or title)", [f"{old} -> {new}" for old, new in changes["renamed"]]),
        ("Changed", [f"{key}: {', '.join(names)}" for key, names in changes["changed"]]),
        ("Cleanup rules (data/publications-rules.json): entries each rule changed in this export, and why",
         [f"{rule['id']}: {len(rule_hits[rule['id']])}. {rule['reason']}" for rule in rules]),
        ("Overrides (data/publications-overrides.json)", override_log or ["none"]),
        ("Needs attention: published anyway, fix with a rule or an override", attention),
    ]
    for title, items in sections:
        if items:
            lines += ["", f"{title}:"] + [wrap(item, "  ") for item in items]
    return "\n".join(lines) + "\n"


def run(arguments):
    rules = json.loads(RULES_PATH.read_text(encoding="utf-8"))
    overrides = json.loads(OVERRIDES_PATH.read_text(encoding="utf-8"))
    state = json.loads(FETCH_STATE_PATH.read_text(encoding="utf-8")) if FETCH_STATE_PATH.exists() else {}
    previous_source = SOURCE_PATH.read_bytes() if SOURCE_PATH.exists() else None
    url = rules["source"]["url"]

    if arguments.source_file:
        raw, validators, origin = Path(arguments.source_file).read_bytes(), {"etag": None, "lastModified": None}, f"{url} (downloaded by hand)"
    elif arguments.no_fetch:
        if previous_source is None:
            raise SyncError(f"--no-fetch: {SOURCE_PATH} does not exist yet")
        raw, validators, origin = previous_source, None, f"{url} (stored export, rebuilt after a rule book or override change)"
    else:
        raw, validators = fetch(url, state)
        if raw is None:
            print("304 Not Modified: the SCI export is unchanged; nothing to do.")
            return None
        origin = url

    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError as error:
        raise SyncError(f"the export is not valid UTF-8 ({error}); a rule cannot fix this, ask SCI IT")
    if not text.startswith(rules["source"]["requiredHeader"]):
        raise SyncError(f"the export does not start with {rules['source']['requiredHeader']!r}; got {text[:80]!r}")
    export_header = next(iter(re.findall(r"^%%: (Updated .*)$", text, re.MULTILINE)), "no Updated line")
    source_entries, parse_errors = parse_bibtex(text)
    if previous_source is not None:
        num_previous = len(parse_bibtex(previous_source.decode("utf-8"))[0])
        if len(source_entries) < rules["safety"]["minimumSourceEntryFraction"] * num_previous:
            raise SyncError(f"the export has {len(source_entries)} readable entries, the stored one {num_previous}: "
                            "refusing to publish")
    wanted_names = [re.escape(name_key(name)) for name in rules["selection"]["anyName"]]
    for key, error in parse_errors.items():
        record = text[text.index("{" + key + ","):][:2000]
        if any(re.search(name, name_key(record)) for name in wanted_names):
            raise SyncError(f"a selected entry cannot be read: {error}")

    override_log = apply_patches(source_entries, overrides)
    selected = [entry for entry in source_entries if is_selected(entry, rules["selection"])]
    rule_hits = clean(selected, rules["rules"])
    entries, exclude_and_add_log = exclude_and_add(selected, overrides, {entry.key for entry in source_entries})
    override_log += exclude_and_add_log
    entries.sort(key=lambda entry: -year_of(entry))
    published_text = format_bibtex(entries)

    previous_entries = parse_bibtex(PUBLISHED_PATH.read_text(encoding="utf-8"))[0] if PUBLISHED_PATH.exists() else []
    if len(entries) < len(previous_entries) - rules["safety"]["maximumSelectedEntryDrop"]:
        raise SyncError(f"{len(entries)} entries would be published, {len(previous_entries)} are now: refusing to publish")
    attention = site_parser_problems(published_text, entries) + leftover_latex(entries)
    changes = describe_changes(previous_entries, entries)

    SOURCE_PATH.parent.mkdir(parents=True, exist_ok=True)
    SOURCE_PATH.write_bytes(raw)
    if validators is not None:
        FETCH_STATE_PATH.write_text(json.dumps({"url": url, **validators, "exportHeader": export_header,
                                                "sha256": hashlib.sha256(raw).hexdigest()}, indent=2) + "\n", encoding="utf-8")
    PUBLISHED_PATH.write_text(published_text, encoding="utf-8")
    return commit_message(origin, arguments.no_fetch, export_header, len(source_entries), len(selected), changes,
                          rule_hits, rules["rules"], override_log, attention)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    source = parser.add_mutually_exclusive_group()
    source.add_argument("--no-fetch", action="store_true")
    source.add_argument("--source-file")
    parser.add_argument("--commit-message-file")
    arguments = parser.parse_args()
    try:
        message = run(arguments)
    except SyncError as error:
        print(f"error: {error}", file=sys.stderr)
        sys.exit(1)
    if message is None:
        return
    if arguments.commit_message_file:
        Path(arguments.commit_message_file).write_text(message, encoding="utf-8")
    print(message)


if __name__ == "__main__":
    main()
